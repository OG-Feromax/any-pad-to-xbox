"""Drift detection: the check this project never had, and the one that matters now.

Today's bug was not that `/etc` was stale — it was that *nothing said so*. The code moved
to a commit that changed rule generation, the installed rules stayed from August, and the
UI showed a green bar the whole time.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

import any_pad_to_xbox.core.installer as installer
from any_pad_to_xbox.core import system
from any_pad_to_xbox.core.installer import InstallSources, desired_files, drift
from conftest import make_profile

PROFILES = {"0079:0006": make_profile("0079:0006", "DragonRise Fliperama")}

# The rules as they sat on disk before the hide feature existed. The bridge half is
# byte-identical to what the current code generates -- the August incident was purely a
# missing file, which is why a content check on the files that exist was never enough.
AUGUST_BRIDGE_RULES = """# Generated by any-pad-to-xbox — do not edit by hand

# DragonRise Fliperama (0079:0006)
ACTION=="add", SUBSYSTEM=="input", KERNEL=="event*", ATTRS{idVendor}=="0079", ATTRS{idProduct}=="0006", RUN+="/bin/sleep 1", TAG+="systemd", ENV{SYSTEMD_WANTS}="xboxdrv@%k.service"
ACTION=="remove", SUBSYSTEM=="input", KERNEL=="event*", ATTRS{idVendor}=="0079", ATTRS{idProduct}=="0006", RUN+="/bin/systemctl stop xboxdrv@%k.service"

"""


def write_installed(profiles, sources=InstallSources()):
    """Materialize a system that already matches `profiles`."""
    for path, content in desired_files(profiles, sources).items():
        path.write_text(content, encoding="utf-8")


@pytest.fixture
def fake_system(tmp_path, monkeypatch):
    """Repoint every installed path at a scratch tree, as if this were the whole system.

    All seven, plus a locked-down `InstallSources.resolve()`: a test that forgets to pass
    `sources` must not end up writing to `/usr/local` — which it really did until this
    fixture was complete, and would have succeeded under a root CI runner.
    """
    etc = tmp_path / "etc"
    etc.mkdir()
    usr_local = tmp_path / "usr-local"
    usr_local.mkdir()
    targets = {
        "SYSTEM_PROFILES": etc / "profiles.json",
        "UDEV_RULES_PATH": etc / "99-any-pad-to-xbox.rules",
        "UDEV_HIDE_RULES_PATH": etc / "65-any-pad-to-xbox-hide.rules",
        "DIAG_NO_GRAB_FLAG": etc / "diag_no_grab",
        "RUNNER_PATH": usr_local / "any-pad-to-xbox-runner",
        "BRIDGE_PATH": usr_local / "xpad_bridge.py",
        "SERVICE_PATH": usr_local / "xboxdrv@.service",
    }
    for name, path in targets.items():
        monkeypatch.setattr(installer, name, path)
    monkeypatch.setattr(
        installer.InstallSources, "resolve", classmethod(lambda cls: cls())
    )
    return targets


@pytest.fixture
def fake_root(tmp_path, monkeypatch):
    """Installed files for check_system() to find, all valid."""
    etc = tmp_path / "root"
    etc.mkdir()
    unit = etc / "xboxdrv@.service"
    unit.write_text("ExecStart=/usr/local/bin/any-pad-to-xbox-runner %i\n", encoding="utf-8")
    profiles = etc / "profiles.json"
    profiles.write_text('{"version": 1, "profiles": {}}\n', encoding="utf-8")
    for name in ("bridge.py", "runner"):
        (etc / name).write_text("", encoding="utf-8")
    monkeypatch.setattr(system, "BRIDGE_PATH", etc / "bridge.py")
    monkeypatch.setattr(system, "RUNNER_PATH", etc / "runner")
    monkeypatch.setattr(system, "SERVICE_PATH", unit)
    monkeypatch.setattr(system, "SYSTEM_CONFIG_DIR", etc)
    monkeypatch.setattr(system, "SYSTEM_PROFILES", profiles)
    # Pinned: otherwise the host's real /etc/any-pad-to-xbox/diag_no_grab decides
    # whether diagnostics show up, making these assertions machine-dependent.
    monkeypatch.setattr(system, "DIAG_NO_GRAB_FLAG", etc / "diag_no_grab")
    return etc


class TestDesiredFiles:
    def test_keys_are_installed_paths_not_staging_paths(self, tmp_path):
        keys = set(desired_files(PROFILES, InstallSources()))
        assert all(str(k).startswith("/") for k in keys)
        assert not any(str(tmp_path) in str(k) for k in keys)

    def test_only_generated_files_without_sources(self):
        assert len(desired_files(PROFILES, InstallSources())) == 3

    def test_absent_sources_are_not_desired(self, tmp_path):
        """An AUR checkout cannot verify the runner, so it must not report it stale."""
        sources = InstallSources(runner=tmp_path / "nope.py")
        assert len(desired_files(PROFILES, sources)) == 3

    def test_present_sources_are_verifiable(self, tmp_path):
        sources = InstallSources(
            runner=_file(tmp_path, "runner"),
            bridge=_file(tmp_path, "bridge"),
            unit=_file(tmp_path, "unit"),
        )
        assert len(desired_files(PROFILES, sources)) == 6


class TestDrift:
    def test_clean_system_has_no_drift(self, fake_system):
        write_installed(PROFILES)
        assert drift(PROFILES, sources=InstallSources()) == []

    def test_reports_the_august_scenario(self, fake_system):
        """The real incident: everything that existed was correct, one file was missing."""
        desired = desired_files(PROFILES, InstallSources())
        fake_system["SYSTEM_PROFILES"].write_text(desired[installer.SYSTEM_PROFILES], encoding="utf-8")
        fake_system["UDEV_RULES_PATH"].write_text(AUGUST_BRIDGE_RULES, encoding="utf-8")

        stale = drift(PROFILES, sources=InstallSources())
        assert stale == [fake_system["UDEV_HIDE_RULES_PATH"]]

    def test_identical_bridge_rules_are_not_reported(self, fake_system):
        """Guard for the above: the August text really is what we generate today."""
        fake_system["UDEV_RULES_PATH"].write_text(AUGUST_BRIDGE_RULES, encoding="utf-8")
        assert fake_system["UDEV_RULES_PATH"] not in drift(
            PROFILES, sources=InstallSources()
        )

    def test_missing_file_counts_as_drift(self, fake_system):
        assert len(drift(PROFILES, sources=InstallSources())) == 3

    def test_one_extra_newline_is_drift(self, fake_system):
        write_installed(PROFILES)
        rules = fake_system["UDEV_HIDE_RULES_PATH"]
        rules.write_text(rules.read_text(encoding="utf-8") + "\n", encoding="utf-8")
        assert drift(PROFILES, sources=InstallSources()) == [rules]

    def test_unreadable_path_is_drift_not_a_crash(self, fake_system):
        write_installed(PROFILES)
        rules = fake_system["UDEV_RULES_PATH"]
        rules.unlink()
        rules.mkdir()  # read_text raises IsADirectoryError
        assert rules in drift(PROFILES, sources=InstallSources())

    def test_source_edited_after_install_is_drift(self, fake_system, tmp_path):
        runner = _file(tmp_path, "runner")
        sources = InstallSources(runner=runner)
        write_installed(PROFILES, sources)
        assert drift(PROFILES, sources=sources) == []
        runner.write_text("runner body edited after install", encoding="utf-8")
        assert drift(PROFILES, sources=sources) == [installer.RUNNER_PATH]

    def test_diag_flag_state_is_drift(self, fake_system):
        write_installed(PROFILES)
        assert drift(PROFILES, sources=InstallSources(), diag_no_grab=False) == []
        assert drift(PROFILES, sources=InstallSources(), diag_no_grab=True) == [
            fake_system["DIAG_NO_GRAB_FLAG"]
        ]


class TestStatusWiring:
    def test_drift_surfaces_in_the_status(self, fake_root, monkeypatch):
        """The bar must warn even though every file it checks for exists."""
        monkeypatch.setattr(
            system, "drift", lambda _p: [Path("/etc/udev/rules.d/65-x.rules")]
        )
        status = system.check_system()
        assert status.integration_installed is True
        assert status.system_stale is True
        assert any("click Enable" in d for d in status.details)

    def test_no_drift_adds_no_warning(self, fake_root, monkeypatch):
        monkeypatch.setattr(system, "drift", lambda _p: [])
        status = system.check_system()
        assert status.system_stale is False
        assert not any("Enable" in d for d in status.details)

    def test_unreadable_profiles_cannot_break_the_status(self, fake_root, monkeypatch):
        """A half-written /etc file must not raise through the UI's status refresh."""
        fake_root.joinpath("profiles.json").write_text("{not json", encoding="utf-8")
        monkeypatch.setattr(system, "drift", lambda _p: [])
        status = system.check_system()
        assert status.integration_installed is True
        assert status.system_stale is False

    def test_diagnostics_flag_is_reported_as_a_mode_not_a_stale_file(self, fake_root, monkeypatch):
        """Calling diag_no_grab a "file behind this app" read like an install problem and
        hid the fact that actually bites: the pad is not grabbed, so games see it twice."""
        monkeypatch.setattr(system, "drift", lambda _p: [system.DIAG_NO_GRAB_FLAG])
        fake_root.joinpath("diag_no_grab").write_text("", encoding="utf-8")
        status = system.check_system()
        assert status.diag_enabled is True
        assert status.system_stale is False, "a mode is not an out-of-date file"
        assert any("Diagnostics mode is ON" in d for d in status.details)
        assert not any("behind this app" in d for d in status.details)

    def test_diagnostics_shows_even_when_the_app_agrees_with_the_flag(self, fake_root):
        """Started with the variable and flag written = no drift at all, but games still
        double the pad. The warning cannot depend on a mismatch existing."""
        fake_root.joinpath("diag_no_grab").write_text("", encoding="utf-8")
        status = system.check_system()
        assert status.diag_enabled is True

    def test_env_on_without_the_flag_says_enable_writes_it(self, fake_root, monkeypatch):
        monkeypatch.setattr(system, "drift", lambda _p: [system.DIAG_NO_GRAB_FLAG])
        status = system.check_system()
        assert status.diag_enabled is False
        assert any("no flag yet" in d for d in status.details)


class TestReapplyIsANoOpWhenClean:
    """`--reapply` restarts the bridge, which blinks the virtual pad out of a game."""

    def test_skips_escalation_when_nothing_differs(self, monkeypatch, capsys):
        from any_pad_to_xbox import __main__ as entry

        monkeypatch.setattr(installer, "drift", lambda *a, **k: [])
        monkeypatch.setattr(
            installer,
            "run_privileged",
            lambda *_: pytest.fail("--reapply must not escalate when there is no drift"),
        )
        assert entry._cli_main(["--reapply"]) == 0
        assert "nothing to apply" in capsys.readouterr().out

    def test_lists_what_it_will_write_then_applies(self, monkeypatch, capsys):
        from any_pad_to_xbox import __main__ as entry

        calls = []

        def fake_run(script):
            calls.append(script)
            return subprocess.CompletedProcess(["pkexec"], 0, "OK\n", "")

        monkeypatch.setattr(
            installer, "drift", lambda *a, **k: [Path("/etc/udev/rules.d/65-x.rules")]
        )
        monkeypatch.setattr(installer, "run_privileged", fake_run)
        assert entry._cli_main(["--reapply"]) == 0

        out = capsys.readouterr().out
        assert "/etc/udev/rules.d/65-x.rules" in out
        assert len(calls) == 1, "expected exactly one privileged run"


    def test_diagnostics_flag_is_labelled_as_a_mode_in_the_plan(self, monkeypatch, capsys):
        """"Updating /etc/any-pad-to-xbox/diag_no_grab" alone reads like a corrupt file."""
        from any_pad_to_xbox import __main__ as entry
        from any_pad_to_xbox.core.installer import DIAG_NO_GRAB_FLAG

        monkeypatch.setattr(installer, "drift", lambda *a, **k: [DIAG_NO_GRAB_FLAG])
        monkeypatch.setattr(
            installer,
            "run_privileged",
            lambda _script: subprocess.CompletedProcess(["pkexec"], 0, "OK\n", ""),
        )
        assert entry._cli_main(["--reapply"]) == 0
        assert "diagnostics no-grab flag" in capsys.readouterr().out


def _file(tmp_path, name):
    target = tmp_path / name
    target.write_text(f"{name} body", encoding="utf-8")
    return target
