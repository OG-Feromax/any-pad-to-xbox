"""udev rule generation — the two files that decide what the system actually does.

These generators write text that runs with root privileges and is invisible until a
pad is plugged in, so the cheap place to catch a regression is here.
"""

from __future__ import annotations

from conftest import make_profile

from any_pad_to_xbox import UDEV_HIDE_RULES_PATH, UDEV_RULES_PATH
from any_pad_to_xbox.core.system import generate_hide_rules, generate_udev_rules

HEADER = "# Generated by any-pad-to-xbox"


class TestBridgeRules:
    """99-any-pad-to-xbox.rules: spawn/stop the per-pad bridge unit on hotplug."""

    def test_targets_the_pads_vendor_and_product(self, two_pads):
        text = generate_udev_rules(two_pads)
        assert 'ATTRS{idVendor}=="0079"' in text
        assert 'ATTRS{idProduct}=="0006"' in text

    def test_add_wants_the_systemd_unit(self, two_pads):
        text = generate_udev_rules(two_pads)
        assert 'ACTION=="add"' in text
        assert 'ENV{SYSTEMD_WANTS}="xboxdrv@%k.service"' in text
        assert 'TAG+="systemd"' in text

    def test_remove_stops_the_unit(self, two_pads):
        """Without this the bridge keeps holding a grab on a vanished device."""
        text = generate_udev_rules(two_pads)
        assert 'ACTION=="remove"' in text
        assert "/bin/systemctl stop xboxdrv@%k.service" in text

    def test_only_event_nodes_start_units(self, two_pads):
        """js* shares the same vendor/product; matching it would double the units."""
        text = generate_udev_rules(two_pads)
        for line in text.splitlines():
            if line.startswith("ACTION="):
                assert 'KERNEL=="event*"' in line

    def test_disabled_profile_is_not_wired(self):
        pads = {"0079:0006": make_profile("0079:0006", enabled=False)}
        assert "0079" not in generate_udev_rules(pads)

    def test_unmapped_profile_is_not_wired(self):
        """An enabled pad with no mapping would produce a dead virtual controller."""
        pads = {"0079:0006": make_profile("0079:0006", buttons={}, axes={})}
        assert "0079" not in generate_udev_rules(pads)

    def test_is_marked_generated(self, two_pads):
        assert generate_udev_rules(two_pads).startswith(HEADER)

    def test_output_is_deterministic(self, two_pads):
        """Same profiles in different insertion order must give the same bytes."""
        shuffled = {k: two_pads[k] for k in reversed(list(two_pads))}
        assert generate_udev_rules(two_pads) == generate_udev_rules(shuffled)


class TestHideRules:
    """65-any-pad-to-xbox-hide.rules: keep mapped physical pads out of game lists."""

    def test_clears_the_joystick_tag(self, two_pads):
        """The whole point: enumerators (SDL, RetroArch udev driver) filter on this."""
        assert 'ENV{ID_INPUT_JOYSTICK}=""' in generate_hide_rules(two_pads)

    def test_re_adds_uaccess(self, two_pads):
        """Clearing the tag also drops the automatic uaccess the tag granted.

        Without the re-add the GUI and bridge lose read access to the physical pad
        for users outside the input group — trading a duplicate controller for a
        broken app.
        """
        assert 'TAG+="uaccess"' in generate_hide_rules(two_pads)

    def test_does_not_start_anything(self, two_pads):
        """Hiding is a tag operation; ACTION/systemd here would spawn duplicate units."""
        text = generate_hide_rules(two_pads)
        assert "ACTION=" not in text
        assert "SYSTEMD_WANTS" not in text

    def test_covers_every_event_and_joystick_node(self, two_pads):
        """No KERNEL filter: the physical js* node must lose the tag too."""
        text = generate_hide_rules(two_pads)
        assert "KERNEL=" not in text
        assert 'SUBSYSTEM=="input"' in text

    def test_disabled_and_unmapped_pads_stay_visible(self):
        pads = {
            "0079:0006": make_profile("0079:0006", enabled=False),
            "1b4f:9206": make_profile("1b4f:9206", buttons={}, axes={}),
        }
        text = generate_hide_rules(pads)
        assert text.startswith(HEADER)
        assert "0079" not in text
        assert "1b4f" not in text

    def test_both_generators_agree_on_which_pads_are_covered(self, two_pads):
        """A pad hidden but not bridged (or bridged but not hidden) is a user-visible bug.

        Both files filter on enabled+has_mapping; this locks them to the same set so
        editing one filter cannot silently diverge from the other.
        """
        def covered(text: str) -> set[str]:
            return {
                line.split("# ")[1].split(" (")[1].rstrip(")")
                for line in text.splitlines()
                if line.startswith("# ") and "(" in line and not line.startswith(HEADER)
            }

        assert covered(generate_udev_rules(two_pads)) == covered(generate_hide_rules(two_pads))


class TestRuleFilePaths:
    """The filenames carry meaning to udev; they are not arbitrary."""

    def test_hide_rules_sort_before_uaccess(self):
        """Rules are applied in lexical order across every rules.d dir.

        /lib/udev/rules.d/70-uaccess.rules reads ID_INPUT_JOYSTICK to grant access,
        so the hide file has to run first — and its uaccess re-add has to land in the
        same pass. Renaming 65- to anything above 70 silently breaks pad access.
        """
        assert UDEV_HIDE_RULES_PATH.name < "70-uaccess.rules"

    def test_bridge_rules_sort_last(self):
        assert UDEV_RULES_PATH.name > "70-uaccess.rules"

    def test_both_live_in_the_admin_dropin_dir(self):
        assert UDEV_RULES_PATH.parent == UDEV_HIDE_RULES_PATH.parent

    def test_the_two_files_have_different_names(self):
        """Same name in the same dir = one install clobbers the other."""
        assert UDEV_RULES_PATH.name != UDEV_HIDE_RULES_PATH.name
