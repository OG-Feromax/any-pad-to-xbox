@dataclass
class SystemStatus:
    bridge_installed: bool
    uinput_ok: bool
    integration_installed: bool
    runner_ok: bool
    service_ok: bool
    config_dir_ok: bool
    in_input_group: bool
    details: list[str]

    # Back-compat for older UI that checked xboxdrv_installed
    @property
    def xboxdrv_installed(self) -> bool:
        return self.bridge_installed


def check_system() -> SystemStatus:
    details: list[str] = []
    bridge_ok = BRIDGE_PATH.exists() or packaging_path("xpad_bridge.py").exists()
    uinput_ok = Path("/dev/uinput").exists()
    if not uinput_ok:
        details.append("Virtual controller support missing — try: sudo modprobe uinput")
    runner_ok = RUNNER_PATH.exists() and RUNNER_PATH.is_file()
    service_ok = False
    if SERVICE_PATH.exists():
        try:
            text = SERVICE_PATH.read_text(encoding="utf-8")
            service_ok = "any-pad-to-xbox-runner" in text
        except OSError:
            service_ok = False
    config_ok = SYSTEM_CONFIG_DIR.is_dir() and SYSTEM_PROFILES.exists()
    # Bridge file on disk after install is what matters for hotplug
    bridge_system = BRIDGE_PATH.exists()
    if not bridge_system:
        details.append("System helper not installed yet.")
    integration = runner_ok and service_ok and config_ok and bridge_system
    if not integration:
        details.append("System setup is not complete.")

    in_input = False
    try:
        out = subprocess.check_output(["id", "-nG"], text=True)
        in_input = "input" in out.split()
    except Exception:
        in_input = False
    if not in_input:
        details.append("User not in the input group (optional; recommended for live preview).")

    return SystemStatus(
        bridge_installed=bridge_system or bridge_ok,
        uinput_ok=uinput_ok,
        integration_installed=integration,
        runner_ok=runner_ok,
        service_ok=service_ok,
        config_dir_ok=config_ok,
        in_input_group=in_input,
        details=details,
    )


def generate_udev_rules(profiles: dict[str, Profile]) -> str:
    lines = [
        "# Generated by any-pad-to-xbox — do not edit by hand",
        "",
    ]
    for key, profile in sorted(profiles.items()):
        if not profile.enabled or not profile.has_mapping():
            continue
        vendor, product = key.split(":", 1)
        lines.append(f"# {profile.name} ({key})")
        lines.append(
            f'ACTION=="add", SUBSYSTEM=="input", KERNEL=="event*", '
            f'ATTRS{{idVendor}}=="{vendor}", ATTRS{{idProduct}}=="{product}", '
            f'RUN+="/bin/sleep 1", TAG+="systemd", ENV{{SYSTEMD_WANTS}}="xboxdrv@%k.service"'
        )
        lines.append(
            f'ACTION=="remove", SUBSYSTEM=="input", KERNEL=="event*", '
            f'ATTRS{{idVendor}}=="{vendor}", ATTRS{{idProduct}}=="{product}", '
            f'RUN+="/bin/systemctl stop xboxdrv@%k.service"'
        )
        lines.append("")
    return "\n".join(lines) + "\n"


def generate_hide_rules(profiles: dict[str, Profile]) -> str:
    """Hide mapped physical pads from games so only the virtual Xbox pad shows up.

    Grabbing the pad blocks its events but not enumeration: RetroArch/SDL list
    every node tagged ID_INPUT_JOYSTICK, so the silent physical pad appears as a
    duplicate. Clearing the tag also drops the automatic uaccess, so it is
    re-added to keep the pad readable by the GUI for users outside `input`.
    """
    lines = [
        "# Generated by any-pad-to-xbox — do not edit by hand",
        "",
    ]
    for key, profile in sorted(profiles.items()):
        if not profile.enabled or not profile.has_mapping():
            continue
        vendor, product = key.split(":", 1)
        lines.append(f"# {profile.name} ({key})")
        lines.append(
            f'SUBSYSTEM=="input", '
            f'ATTRS{{idVendor}}=="{vendor}", ATTRS{{idProduct}}=="{product}", '
            f'ENV{{ID_INPUT_JOYSTICK}}="", TAG+="uaccess"'
        )
        lines.append("")
    return "\n".join(lines) + "\n"


def _pkexec_script(script: str) -> subprocess.CompletedProcess[str]:
    with tempfile.NamedTemporaryFile("w", suffix=".sh", delete=False) as fh:
        fh.write(script)
        path = fh.name
    os.chmod(path, 0o700)
    try:
        return subprocess.run(
            ["pkexec", "bash", path],
            capture_output=True,
            text=True,
            check=False,
        )
    finally:
        try:
            os.unlink(path)
        except OSError:
            pass


def purge_legacy_xboxdrv_bash() -> str:
    """Shell snippet: disable old xboxdrv paths so only our bridge owns the pad."""
    return r"""
# --- purge legacy xboxdrv (binary daemon + old hotplug) ---
systemctl stop xboxdrv.service 2>/dev/null || true
systemctl disable xboxdrv.service 2>/dev/null || true
systemctl mask xboxdrv.service 2>/dev/null || true
# Kill leftover userspace xboxdrv binaries (not our python bridge)
pkill -x xboxdrv 2>/dev/null || true
sleep 0.2
pkill -x xboxdrv 2>/dev/null || true
# Retire old hotplug script / udev if still present
if [[ -f /usr/local/bin/xboxdrv_instance.sh ]]; then
  mv -f /usr/local/bin/xboxdrv_instance.sh /usr/local/bin/xboxdrv_instance.sh.bak
fi
if [[ -f /etc/udev/rules.d/99-joystick.rules ]]; then
  # Only retire if it looks like the old xboxdrv hotplug rule
  if grep -qE 'xboxdrv_instance|xboxdrv@' /etc/udev/rules.d/99-joystick.rules 2>/dev/null; then
    mv -f /etc/udev/rules.d/99-joystick.rules /etc/udev/rules.d/99-joystick.rules.bak
  fi
fi
"""


def install_integration() -> tuple[bool, str]:
    """Install runner, bridge, unit, config dir via pkexec."""
    runner_src = packaging_path("xboxdrv_runner.py")
    bridge_src = packaging_path("xpad_bridge.py")
    service_src = packaging_path("xboxdrv@.service")
    if not runner_src.exists() or not bridge_src.exists() or not service_src.exists():
        return False, f"Packaging files not found: {runner_src}, {bridge_src}, {service_src}"

    purge = purge_legacy_xboxdrv_bash()
    script = f"""#!/bin/bash
set -euo pipefail
install -d -m 755 /etc/any-pad-to-xbox
install -d -m 755 /usr/local/bin
install -d -m 755 /usr/local/lib/any-pad-to-xbox
install -m 755 "{runner_src}" /usr/local/bin/any-pad-to-xbox-runner
install -m 755 "{bridge_src}" /usr/local/lib/any-pad-to-xbox/xpad_bridge.py
install -m 644 "{service_src}" /etc/systemd/system/xboxdrv@.service
if [[ ! -f /etc/any-pad-to-xbox/profiles.json ]]; then
  echo '{{"version": 1, "require_remote_access": false, "profiles": {{}}}}' > /etc/any-pad-to-xbox/profiles.json
fi
modprobe uinput 2>/dev/null || true
{purge}
# Test-phase no-grab flag (synced from app DIAG_NO_GRAB at apply time too)
if [[ "{DIAG_NO_GRAB}" == "True" ]]; then
  touch /etc/any-pad-to-xbox/diag_no_grab
else
  rm -f /etc/any-pad-to-xbox/diag_no_grab
fi
systemctl daemon-reload
udevadm control --reload
# Restart bridge for any currently connected profiled pads
python3 - <<'PY'
import json, subprocess
from pathlib import Path
data = json.loads(Path("/etc/any-pad-to-xbox/profiles.json").read_text())
wanted = {{
    k.lower() for k, p in (data.get("profiles") or {{}}).items()
    if p.get("enabled", True) and (p.get("evdev_keymap") or p.get("evdev_absmap"))
}}
if not wanted:
    raise SystemExit(0)
for ev in Path("/dev/input").glob("event*"):
    try:
        out = subprocess.check_output(
            ["udevadm", "info", "--query=property", f"--name={{ev}}"], text=True
        )
    except Exception:
        continue
    vendor = product = None
    for line in out.splitlines():
        if line.startswith("ID_VENDOR_ID="):
            vendor = line.split("=", 1)[1].lower()
        elif line.startswith("ID_MODEL_ID="):
            product = line.split("=", 1)[1].lower()
    if not vendor or not product:
        continue
    key = f"{{vendor}}:{{product}}"
    if key not in wanted:
        continue
    unit = f"xboxdrv@{{ev.name}}.service"
    subprocess.run(["systemctl", "stop", unit], check=False, capture_output=True)
    subprocess.run(["systemctl", "reset-failed", unit], check=False, capture_output=True)
    r = subprocess.run(["systemctl", "start", unit], check=False, capture_output=True, text=True)
    print(f"start {{unit}}: {{r.returncode}}")
PY
echo OK
"""
    result = _pkexec_script(script)
    if result.returncode != 0:
        return False, (result.stderr or result.stdout or f"exit {result.returncode}").strip()
    return True, "System component installed."


def apply_profiles(
    profiles: dict[str, Profile],
    start_event: str | None = None,
    stop_event: str | None = None,
) -> tuple[bool, str]:
    """Write system profiles + udev, refresh runner/bridge, optionally start/stop instance.

    One pkexec for the whole operation — pass stop_event to halt a unit without a
    second password prompt (used by Disable).
    """
    json_text = profiles_to_system_json(profiles)
    udev_text = generate_udev_rules(profiles)
    hide_text = generate_hide_rules(profiles)
    runner_src = packaging_path("xboxdrv_runner.py")
    bridge_src = packaging_path("xpad_bridge.py")

    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = Path(tmp)
        profiles_file = tmp_path / "profiles.json"
        udev_file = tmp_path / UDEV_RULES_PATH.name
        hide_file = tmp_path / UDEV_HIDE_RULES_PATH.name
        profiles_file.write_text(json_text, encoding="utf-8")
        udev_file.write_text(udev_text, encoding="utf-8")
        hide_file.write_text(hide_text, encoding="utf-8")

        installs = ""
        if runner_src.exists():
            installs += f'install -m 755 "{runner_src}" /usr/local/bin/any-pad-to-xbox-runner\n'
        if bridge_src.exists():
            installs += (
                'install -d -m 755 /usr/local/lib/any-pad-to-xbox\n'
                f'install -m 755 "{bridge_src}" /usr/local/lib/any-pad-to-xbox/xpad_bridge.py\n'
            )

        if DIAG_NO_GRAB:
            diag_flag_cmd = f'touch "{DIAG_NO_GRAB_FLAG}"\n'
        else:
            diag_flag_cmd = f'rm -f "{DIAG_NO_GRAB_FLAG}"\n'

        start_cmd = ""
        if start_event:
            event = start_event.removeprefix("/dev/input/")
            start_cmd = f"""
{purge_legacy_xboxdrv_bash()}
systemctl stop 'xboxdrv@{event}.service' 2>/dev/null || true
systemctl reset-failed 'xboxdrv@{event}.service' 2>/dev/null || true
# Give previous grab holder time to release the fd
sleep 0.6
systemctl start 'xboxdrv@{event}.service'
sleep 0.4
if ! systemctl is-active --quiet 'xboxdrv@{event}.service'; then
  echo "bridge failed to stay active for {event}" >&2
  systemctl status 'xboxdrv@{event}.service' --no-pager -l >&2 || true
  journalctl -u 'xboxdrv@{event}.service' -n 30 --no-pager >&2 || true
  exit 1
fi
"""
        else:
            parts = [purge_legacy_xboxdrv_bash()]
            if stop_event:
                ev = stop_event.removeprefix("/dev/input/")
                parts.append(
                    f"systemctl stop 'xboxdrv@{ev}.service' 2>/dev/null || true\n"
                    f"systemctl reset-failed 'xboxdrv@{ev}.service' 2>/dev/null || true\n"
                )
            start_cmd = "".join(parts)

        script = f"""#!/bin/bash
set -euo pipefail
install -d -m 755 /etc/any-pad-to-xbox
install -d -m 755 /usr/local/bin
{installs}install -m 644 "{profiles_file}" /etc/any-pad-to-xbox/profiles.json
install -m 644 "{udev_file}" "{UDEV_RULES_PATH}"
install -m 644 "{hide_file}" "{UDEV_HIDE_RULES_PATH}"
{diag_flag_cmd}modprobe uinput 2>/dev/null || true
udevadm control --reload
# "change" re-evaluates the hide rules for pads already plugged in without
# firing the ACTION=="add" bridge rules again.
udevadm trigger --subsystem-match=input --action=change
systemctl daemon-reload
{start_cmd}
echo OK
"""
        result = _pkexec_script(script)
        if result.returncode != 0:
            return False, (result.stderr or result.stdout or f"exit {result.returncode}").strip()
    mode = " (diag no-grab)" if DIAG_NO_GRAB else ""
    return True, "Configuration applied" + mode + "."


def stop_instance(event_node: str) -> tuple[bool, str]:
    event = event_node.removeprefix("/dev/input/")
    script = f"""#!/bin/bash
set -euo pipefail
systemctl stop 'xboxdrv@{event}.service' 2>/dev/null || true
echo OK
"""
    result = _pkexec_script(script)
    if result.returncode != 0:
        return False, (result.stderr or result.stdout or "").strip()
    return True, "Stopped."


def start_instance(event_node: str) -> tuple[bool, str]:
    event = event_node.removeprefix("/dev/input/")
    script = f"""#!/bin/bash
set -euo pipefail
systemctl start 'xboxdrv@{event}.service'
echo OK
"""
    result = _pkexec_script(script)
    if result.returncode != 0:
        return False, (result.stderr or result.stdout or "").strip()
    return True, "Started."


def is_instance_active(event_node: str) -> bool:
    event = event_node.removeprefix("/dev/input/")
    try:
        r = subprocess.run(
            ["systemctl", "is-active", f"xboxdrv@{event}.service"],
            capture_output=True,
            text=True,
            check=False,
        )
        return r.stdout.strip() == "active"
    except Exception:
        return False


def xboxdrv_install_hint() -> str:
    """Legacy name — bridge needs no AUR package."""
    return "sudo modprobe uinput"


def bridge_install_hint() -> str:
    return "Click Install (asks for password)"
