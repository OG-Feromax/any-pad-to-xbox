"""udev rule text generation — pure, no I/O, no privileges.

Two files come out of this module and they answer different questions:

* `99-any-pad-to-xbox.rules` starts/stops the per-pad bridge on hotplug.
* `65-any-pad-to-xbox-hide.rules` keeps the mapped physical pad out of the
  enumerators so games see only the virtual Xbox pad.

Both select the same set of pads (enabled + mapped); if they ever disagree a pad
either gets hidden without a bridge, or bridged while still showing as a duplicate.
"""

from __future__ import annotations

from any_pad_to_xbox.core.profiles import Profile

GENERATED_HEADER = "# Generated by any-pad-to-xbox — do not edit by hand"


def _covered_pads(profiles: dict[str, Profile]) -> list[tuple[str, Profile]]:
    """Enabled pads that have at least one mapping, in stable key order."""
    return [
        (key, profile)
        for key, profile in sorted(profiles.items())
        if profile.enabled and profile.has_mapping()
    ]


def generate_udev_rules(profiles: dict[str, Profile]) -> str:
    lines = [GENERATED_HEADER, ""]
    for key, profile in _covered_pads(profiles):
        vendor, product = key.split(":", 1)
        lines.append(f"# {profile.name} ({key})")
        lines.append(
            f'ACTION=="add", SUBSYSTEM=="input", KERNEL=="event*", '
            f'ATTRS{{idVendor}}=="{vendor}", ATTRS{{idProduct}}=="{product}", '
            f'RUN+="/bin/sleep 1", TAG+="systemd", ENV{{SYSTEMD_WANTS}}="xboxdrv@%k.service"'
        )
        lines.append(
            f'ACTION=="remove", SUBSYSTEM=="input", KERNEL=="event*", '
            f'ATTRS{{idVendor}}=="{vendor}", ATTRS{{idProduct}}=="{product}", '
            f'RUN+="/bin/systemctl stop xboxdrv@%k.service"'
        )
        lines.append("")
    return "\n".join(lines) + "\n"


def generate_hide_rules(profiles: dict[str, Profile]) -> str:
    """Hide mapped physical pads from games so only the virtual Xbox pad shows up.

    Grabbing the pad blocks its events but not enumeration: RetroArch/SDL list
    every node tagged ID_INPUT_JOYSTICK, so the silent physical pad appears as a
    duplicate. Clearing the tag also drops the automatic uaccess, so it is
    re-added to keep the pad readable by the GUI for users outside `input`.
    """
    lines = [GENERATED_HEADER, ""]
    for key, profile in _covered_pads(profiles):
        vendor, product = key.split(":", 1)
        lines.append(f"# {profile.name} ({key})")
        lines.append(
            f'SUBSYSTEM=="input", '
            f'ATTRS{{idVendor}}=="{vendor}", ATTRS{{idProduct}}=="{product}", '
            f'ENV{{ID_INPUT_JOYSTICK}}="", TAG+="uaccess"'
        )
        lines.append("")
    return "\n".join(lines) + "\n"
